import test from 'node:test';
import assert from 'node:assert/strict';
import {createDashboardServer} from './server.mjs';
import {mkdtemp,writeFile,mkdir,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import path from 'node:path';
import {createHash} from 'node:crypto';
test('server exposes only named dashboard assets and gives actionable missing-data response',async(t)=>{
  const server=createDashboardServer('/nonexistent/dashboard-fixture.json');
  await new Promise((resolve,reject)=>{server.once('error',reject);server.listen(0,'127.0.0.1',resolve);});
  t.after(()=>new Promise(resolve=>server.close(resolve)));
  const url=`http://127.0.0.1:${server.address().port}`;
  const home=await fetch(url);assert.equal(home.status,200);assert.match(await home.text(),/가격 예측, 실제와 나란히/);
  for(const p of ['/.env','/data/agri.sqlite','/../README.md','/%2e%2e/README.md','/server.mjs'])assert.equal((await fetch(url+p)).status,404);
  const missing=await fetch(url+'/api/results');assert.equal(missing.status,503);assert.match((await missing.json()).message,/agri_data.dashboard/);
  assert.equal((await fetch(url,{method:'POST'})).status,405);
  assert.match(home.headers.get('content-security-policy'),/frame-ancestors 'none'/);
});
test('server attaches significance only to the exact prediction file and matching evaluation range',async(t)=>{
  const dir=await mkdtemp(path.join(tmpdir(),'agri-significance-'));
  const file=path.join(dir,'dashboard.json'),sig=path.join(dir,'significance.json');
  const payload=JSON.stringify({meta:{evaluationStart:'2017-01-01',evaluationEnd:'2018-12-20',statisticalSignificance:{stale:true}}});
  await writeFile(file,payload);
  const server=createDashboardServer(file);
  await new Promise((resolve,reject)=>{server.once('error',reject);server.listen(0,'127.0.0.1',resolve);});
  t.after(async()=>{await new Promise(resolve=>server.close(resolve));await rm(dir,{recursive:true,force:true});});
  const url=`http://127.0.0.1:${server.address().port}/api/results`;
  let data=await(await fetch(url)).json();assert.equal(data.meta.statisticalSignificanceStatus,'missing');assert.equal(data.meta.statisticalSignificance,undefined);
  const report={schemaVersion:1,protocol:{inputSha256:createHash('sha256').update(payload).digest('hex'),evaluationStart:'2017-01-01',evaluationEnd:'2018-12-20'},comparisons:[]};
  await writeFile(sig,JSON.stringify(report));data=await(await fetch(url)).json();assert.equal(data.meta.statisticalSignificanceStatus,'verified');
  await writeFile(file,payload+'\n');data=await(await fetch(url)).json();assert.equal(data.meta.statisticalSignificanceStatus,'mismatch');assert.equal(data.meta.statisticalSignificance,undefined);
  await writeFile(file,payload);report.protocol.evaluationEnd='2018-12-19';await writeFile(sig,JSON.stringify(report));data=await(await fetch(url)).json();assert.equal(data.meta.statisticalSignificanceStatus,'mismatch');
});
test('market experiment route serves only a complete assessed result',async(t)=>{
  const dir=await mkdtemp(path.join(tmpdir(),'agri-market-'));
  const market=path.join(dir,'market.json');
  const server=createDashboardServer(path.join(dir,'dashboard.json'),path.join(dir,'significance.json'),market);
  await new Promise((resolve,reject)=>{server.once('error',reject);server.listen(0,'127.0.0.1',resolve);});
  t.after(async()=>{await new Promise(resolve=>server.close(resolve));await rm(dir,{recursive:true,force:true});});
  const url=`http://127.0.0.1:${server.address().port}/api/market-experiment`;
  assert.equal((await fetch(url)).status,503);
  const report={schemaVersion:1,status:'incomplete',protocol:{evaluation:['2019-01-01','2020-12-31']},products:Array(5).fill({}),comparisons:Array(20).fill({})};
  await writeFile(market,JSON.stringify(report));assert.equal((await fetch(url)).status,503);
  report.status='complete';await writeFile(market,JSON.stringify(report));
  const response=await fetch(url);assert.equal(response.status,200);assert.equal((await response.json()).status,'complete');
});
test('live route serves the exact immutable artifact named by a safe hash-checked pointer',async(t)=>{
  const dir=await mkdtemp(path.join(tmpdir(),'agri-live-'));
  const live=path.join(dir,'live');
  const runDir=path.join(live,'2026-10-06');
  await mkdir(runDir,{recursive:true});
  const pointerPath=path.join(live,'latest.json');
  const artifact='2026-10-06/20261006T101500+0900-a1b2c3d4.json';
  const report={schemaVersion:1,issueAtKst:'2026-10-06T10:15:00+09:00',sourceCutoffDate:'2026-10-05',products:Array(5).fill({predictions:[]})};
  const raw=JSON.stringify(report);
  await writeFile(path.join(runDir,path.basename(artifact)),raw);
  const pointer={schemaVersion:1,artifact,artifactSha256:createHash('sha256').update(raw).digest('hex'),issueAtKst:report.issueAtKst,sourceCutoffDate:report.sourceCutoffDate};
  const server=createDashboardServer(path.join(dir,'dashboard.json'),path.join(dir,'significance.json'),path.join(dir,'market.json'),pointerPath);
  await new Promise((resolve,reject)=>{server.once('error',reject);server.listen(0,'127.0.0.1',resolve);});
  t.after(async()=>{await new Promise(resolve=>server.close(resolve));await rm(dir,{recursive:true,force:true});});
  const url=`http://127.0.0.1:${server.address().port}/api/live-forecast`;
  assert.equal((await fetch(url)).status,503);
  await writeFile(pointerPath,JSON.stringify(pointer));
  assert.equal((await fetch(url)).status,200);
  await writeFile(path.join(runDir,path.basename(artifact)),raw+'\n');
  assert.equal((await fetch(url)).status,503);
  pointer.artifact='../dashboard.json';await writeFile(pointerPath,JSON.stringify(pointer));
  assert.equal((await fetch(url)).status,503);
});
